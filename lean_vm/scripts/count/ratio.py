"""`Count/RatioData.lean`, `Count/RatioChk*.lean` and `Count/Ratio.lean`: the counts of functions
with no static bound within ratios of their words (`Count/RatioBase.kr_weight`), per opcode.

For each function `f`, `kr<N>J` lists the core indices of the functions its paths reach, `kr<N>C`
their calls by index, and `kr<N>A op` the largest `pathMax g op / fs g` over them in thousandths,
rounded up; the closure and ratio checks are decided in chunks of the indices."""
import os

HDR = '''/-
  LeanVM.Guest.Count.%s

  Generated by `scripts/count/gen.py`; do not edit.
  %s
-/

module

%s
namespace LeanVM.Guest.Count

open LeanVM.Parameters LeanVM.Semantics LeanVM.Guest.Core LeanVM.Guest.Memory LeanVM.Guest.B2C

set_option maxRecDepth 100000

%s@[expose] public section

'''

DOC = '''/-!
# Counts within a ratio of the words

For each function, `kr*J` lists the core indices of the functions its paths reach, `kr*C` their
calls by index (`krClosedAt`), and `kr*A op` the largest `B2C.pathMax g op / B2C.fs g` over them,
in thousandths, rounded up (`krRatioAt`); both decided in chunks of the indices. `kr*_weight`:
every valid tree of the function counts at most `kr*A op / 1000` of `op`'s instructions per word
it allocates.
-/

'''

WEIGHT = '''/-- **`%s`'s counts within its ratios of its words.** -/
theorem kr%s_weight (op : Opcode) : ∀ (rd : Reader) (t : Tree) (args rets : List E),
    t.name = "%s" → t.Valid coreProgram rd args rets → t.BufsOk coreProgram →
      1000 * t.weight (ωArm xmssArmC op) ≤ kr%sA op * t.total fs :=
  fun _ _ _ _ hn hv _ => kr_weight kr%s_closed kr%s_ratio (by decide +kernel)
    ⟨%d, by decide +kernel, by decide +kernel⟩ op hn hv
'''


def blk_callees(ss):
    """`Stmt.blockCallees`, in order."""
    out = []
    for s in ss:
        if s[0] == 'ite': out += blk_callees(s[2]) + blk_callees(s[3])
        elif s[0] == 'match':
            for a in s[2]: out += blk_callees(a)
        elif s[0] == 'call': out.append(s[1])
        elif s[0] == 'callIf': out.append(s[2])
        elif s[0] == 'dispatch': out += list(s[2])
    return out


def wrap(prefix, items, w=100):
    out = []; s = prefix
    for i, it in enumerate(items):
        piece = it + (', ' if i < len(items) - 1 else ']')
        if len(s) + len(piece) > w: out.append(s.rstrip()); s = '    '
        s += piece
    if not items: s += ']'
    out.append(s)
    return '\n'.join(out)


def write(g, roots, opdef, CH=48, W=750):
    D = os.path.join(g.lv, 'LeanVM', 'Guest', 'Count')
    for f in os.listdir(D):
        if f.startswith('RatioChk') or f in ('RatioData.lean', 'Ratio.lean'): os.remove(os.path.join(D, f))
    fsN = lambda j: g.main_frame if j == 1 else max(2, g.fsz[j])
    data, chks, fin = [], [], []
    for N, r in roots:
        J = sorted(g.by[n] for n in g.closure([r]))
        assert g.xj not in J, '%s reaches verify_lean_xmss' % r
        A = [max(-(-1000 * g.pm[j + 1][k] // fsN(j + 1)) for j in J) for k in range(6)]
        def cost(j):
            return len(str(g.fns[j]['body'])) / 1000 + sum(g.by[c] for c in blk_callees(g.fns[j]['body'])) / 100
        chunks = []; cur = []; w = 0
        for j in J:
            if cur and (w + cost(j) > W or len(cur) >= CH): chunks.append(cur); cur = []; w = 0
            cur.append(j); w += cost(j)
        if cur: chunks.append(cur)
        o = ['/-! ## `%s` -/\n' % r]
        for c, ch in enumerate(chunks):
            o.append(wrap('/-- Indices of the functions `%s` reaches, part %d. -/\ndef kr%sJ%d : List ℕ := ['
                          % (r, c, N, c), [str(j) for j in ch]))
        o.append('/-- The core indices of the functions `%s`\'s paths reach. -/\ndef kr%sJ : List ℕ := %s\n'
                 % (r, N, ' ++ '.join('kr%sJ%d' % (N, c) for c in range(len(chunks)))))
        items = ['(%d, [%s])' % (j, ', '.join(str(g.by[c]) for c in blk_callees(g.fns[j]['body'])))
                 for j in J if blk_callees(g.fns[j]['body'])]
        cls = []; cur = []; w = 0
        for it in items:
            if cur and w + len(it) > 3000: cls.append(cur); cur = []; w = 0
            cur.append(it); w += len(it)
        if cur: cls.append(cur)
        for c, cl in enumerate(cls):
            o.append(wrap('/-- Their calls, by index, part %d. -/\ndef kr%sCL%d : List (ℕ × List ℕ) := [' % (c, N, c), cl))
        o.append('/-- Their calls, by index. -/\ndef kr%sCL : List (ℕ × List ℕ) := %s\n'
                 % (N, ' ++ '.join('kr%sCL%d' % (N, c) for c in range(len(cls))) or '[]'))
        o.append('/-- The calls of function `i`, by index. -/\n'
                 'def kr%sC (i : ℕ) : List ℕ := (kr%sCL.lookup i).getD []\n' % (N, N))
        o.append(opdef('kr%sA' % N, '`%s`\'s ratios, in thousandths.' % r, A))
        data.append('\n'.join(o))
        for c in range(len(chunks)):
            nm = 'RatioChk%s%d' % (N, c)
            chks.append(nm)
            body = ('theorem kr%s_closed%d : (kr%sJ%d).all (krClosedAt kr%sJ kr%sC) = true := by\n  decide +kernel\n\n'
                    'theorem kr%s_ratio%d : (kr%sJ%d).all (krRatioAt kr%sA) = true := by\n  decide +kernel\n\n'
                    'end\nend LeanVM.Guest.Count\n' % (N, c, N, c, N, N, N, c, N, c, N))
            open(os.path.join(D, nm + '.lean'), 'w', encoding='utf-8').write(
                HDR % (nm, 'The closure and ratio checks of one chunk of a ratio subtree.',
                       'public import LeanVM.Guest.Count.RatioData\n', '') + body)
        def comb(k):
            acc = 'kr%s_%s0' % (N, k)
            for c in range(1, len(chunks)): acc = 'kr_all_append (%s) kr%s_%s%d' % (acc, N, k, c)
            return acc
        fin.append('theorem kr%s_closed : (kr%sJ).all (krClosedAt kr%sJ kr%sC) = true :=\n  %s\n' % (N, N, N, N, comb('closed')))
        fin.append('theorem kr%s_ratio : (kr%sJ).all (krRatioAt kr%sA) = true :=\n  %s\n' % (N, N, N, comb('ratio')))
        fin.append(WEIGHT % (r, N, r, N, N, N, g.by[r]))
        print('ratio %s: %d functions, %d chunks, A = %s' % (r, len(J), len(chunks), A))
    open(os.path.join(D, 'RatioData.lean'), 'w', encoding='utf-8').write(
        HDR % ('RatioData', 'The subtrees of the ratio bounds: their functions by index, their calls, their ratios.',
               'public import LeanVM.Guest.Count.RatioBase\n', '') + '\n'.join(data) + '\nend\nend LeanVM.Guest.Count\n')
    names = ', '.join('`%s`' % r for _, r in roots)
    open(os.path.join(D, 'Ratio.lean'), 'w', encoding='utf-8').write(
        HDR % ('Ratio', 'The instruction counts of %s\n  within ratios of their words, per opcode.' % names,
               ''.join('public import LeanVM.Guest.Count.%s\n' % n for n in chks), DOC)
        + '\n'.join(fin) + '\nend\nend LeanVM.Guest.Count\n')
