"""`Count/Deployed*.lean`: the numbers of `Budget.deployedBudget Bv`, computed here from the data as
`B1.Main.mainWords` and `Budget.mainInstrs` define them, and proved by `decide +kernel` (each closed
part in its own module, the kernel's string lookups being its cost)."""
import os

DL = ["da_levels__L1_L0", "da_levels__L2_L1", "da_levels__L4_L2", "da_levels__L8_L3",
      "da_levels__L16_L4", "da_levels__L32_L5", "da_levels__L64_L6", "da_levels__L128_L7",
      "da_levels__L256_L8", "da_levels__L512_L9", "da_levels__L1024_L10"]
CL = ['claim_list_last__L%d' % k for k in range(17)]
CCL = ['child_claim_list_last__L%d' % k for k in range(17)]
FIELDS = ['base', 'declared', 'coverage', 'rawXmss', 'rawSphincs', 'rawDa', 'rawDaRows', 'children',
          'childClaims']

HDR = '''/-
  LeanVM.Guest.Count.%s

  Generated by `scripts/count/gen.py`; do not edit.
  %s
-/

module

%s
namespace LeanVM.Guest.Count

open LeanVM.Parameters LeanVM.Semantics LeanVM.Guest.Core LeanVM.Guest.Memory LeanVM.Guest
open LeanVM.Guest.B1.Main (nameSum dlK colC colS clC ccC dvC dvS l5A0 l5A1 l5A2 agA0 agA1 mainWords)

@[expose] public section
%s
end
end LeanVM.Guest.Count
'''


def numbers(g, A, certs):
    fsd = g.fs_words()
    w = g.words_certs()
    def fs(n): return fsd.get(n, 2)
    def SB(n):
        c = w.get(n); return c[2][0] if c and c[0] == 'stat' else 0
    def SK(n):
        c = w.get(n); return c[3][0] if c and c[0] == 'loop' else 0
    for n in DL + CL + CCL: assert n in g.by, n
    v = {}
    v['dlK'] = max(-(-SB(n) // 2 ** j) for j, n in enumerate(DL))
    v['cl'] = sum(SB(n) for n in CL)
    v['ccl'] = sum(fs(n) for n in CCL)
    colC = lambda f, gl: fs(f) + fs('da_vector_cell') + fs(gl)
    colS = lambda rl, gl: 8 + SK(rl) + SK(gl) + 2 * v['dlK']
    v['colC1'] = colC('da_verify_column__L1', '__loop418')
    v['colC0'] = colC('da_verify_column__L0', '__loop420')
    v['clC'] = fs('claim_list_digest') + 13 + SB('list_split') + fs('__loop16') + v['cl']
    v['dvC'] = (fs('da_verify') + 768 + fs('da_row_shape') + fs('__loop24') + SB('da_levels__L128_L7')
                + (65 * fs('__loop20') + 64 * v['colC1']) + (65 * fs('__loop21') + 64 * v['colC0']))
    v['dvS'] = (395 + SK('__loop18') + SK('__loop19') + SK('__loop22') + SK('__loop23') + SK('__loop24')
                + 2 * v['dlK'] + 64 * colS('__loop417', '__loop418') + 64 * colS('__loop419', '__loop420'))
    v['ccC'] = fs('child_claim_list_digest') + 13 + SB('list_split') + fs('__loop17') + v['ccl']
    v['l5A0'] = fs('__loop5')
    v['l5A1'] = fs('__loop5') + 2 + 2 * v['ccC'] + fs('__loop28') + SB('da_list_digest') + SB('statement_digest')
    v['l5A2'] = 17 + fs('__loop17') + fs('__loop28') + fs('cover_da_root')
    v['agA0'] = fs('aggregate_claims') + 97 + SB('batch_sumcheck__L23')
    v['agA1'] = 32 + SK('__loop25') + SK('__loop26') + SK('__loop27')
    base = (fs('main') + 283 + fs('exponent_tables') + 68 + fs('__loop0') + SB('da_list_digest')
            + fs('da_list_digest') + 2 * (v['clC'] + fs('claim_list_digest')) + fs('__loop1') + fs('__loop2')
            + fs('__loop3') + fs('__loop4') + 2 * v['l5A0'] + (v['agA0'] + fs('aggregate_claims'))
            + SB('statement_digest') + fs('statement_digest'))
    words = [base, 13 + SK('__loop16'), 5 + SK('__loop0') + SK('__loop1') + SK('__loop2'), SK('__loop3'),
             SK('__loop4'), v['dvC'] + fs('da_verify') + 2 * fs('cover_da_root'), v['dvS'], 51 + v['l5A1'] + v['agA1'], v['l5A2']]
    instrs = {}
    for lop, P, k in OPS_:
        c = certs[P]
        st = lambda n: c[n][2][0]
        lp = lambda n: c[n][3][0]
        agg = c['aggregate_claims']
        aggC, aggD = agg[2][0], sum(a for _, a in agg[2][1])
        jt = 8473 if lop == 'setConstant' else 0
        acl, adv, a5 = A['Cl'][k], A['Dv'][k], A['L5'][k]
        instrs[lop] = ([g.pm[1][k] + st('exponent_tables') + st('da_list_digest') + st('statement_digest') + jt
                        + 2 * (acl * v['clC'] // 1000 + 1),
                        acl * (13 + SK('__loop16')) // 1000 + 1,
                        lp('__loop0') + lp('__loop1') + lp('__loop2'), lp('__loop3'), lp('__loop4'),
                        adv * v['dvC'] // 1000 + 1 + st('cover_da_root'), adv * v['dvS'] // 1000 + 1,
                        (a5 * v['l5A0'] // 1000 + 1) + 1 + aggC + aggD,
                        a5 * v['l5A2'] // 1000 + 1], a5)
    return v, words, instrs


OPS_ = None


def idx_rw(g, fs=(), sb=(), sk=()):
    """Rewrites of `B2C.fs`, `wSB`, `wSK` at the named functions by their core indices."""
    out = ['fs_idx (j := %d) (f := "%s") (by decide +kernel)' % (g.by[n], n) for n in dict.fromkeys(fs)]
    out += ['wSB_idx (j := %d) (f := "%s") (by decide +kernel)' % (g.by[n], n) for n in dict.fromkeys(sb)]
    out += ['wSK_idx (j := %d) (f := "%s") (by decide +kernel)' % (g.by[n], n) for n in dict.fromkeys(sk)]
    return ',\n    '.join(out)


def write(g, ratio_A, certs, ops):
    global OPS_
    OPS_ = ops
    v, words, instrs = numbers(g, ratio_A, certs)
    D = os.path.join(g.lv, 'LeanVM', 'Guest', 'Count')
    def mod(name, doc, imports, body):
        open(os.path.join(D, name + '.lean'), 'w', encoding='utf-8').write(HDR % (name, doc, imports, body))
    imp0 = 'public import LeanVM.Guest.Budget.DeployedBudget\n'
    mod('DeployedA', 'The DA levels\' words per padded row (`B1.Main.dlK`).', imp0, '''
/-- The DA levels' words per padded row, the largest over the levels. -/
theorem dlK_eq : dlK wSB = %d := by decide +kernel
''' % v['dlK'])
    mod('DeployedA2', 'The claim lists\' last digests\' words over the name lists of `B1.Main.clC`, `B1.Main.ccC`.',
        imp0, '''
/-- The claim lists' last digests' words. -/
theorem cl_sum : nameSum wSB B1.Digest.clNames 17 = %d := by decide +kernel

/-- The children's claim lists' last digests' frames. -/
theorem ccl_sum : nameSum (fun g => B2C.fs g) B1.Digest.cclNames 17 = %d := by decide +kernel
''' % (v['cl'], v['ccl']))
    def thm(name, lhs, val, unf, rws, fs=(), sb=(), sk=()):
        r = idx_rw(g, fs, sb, sk)
        steps = ', '.join(rws) + (',\n    ' if rws and r else '') + r
        return ('theorem %s : %s = %d := by\n  unfold %s\n  rw [%s]\n  decide +kernel\n'
                % (name, lhs, val, unf, steps))
    col1 = thm('colC1_eq', 'colC B2C.fs "da_verify_column__L1" "__loop418"', v['colC1'], 'colC', [],
               fs=['da_verify_column__L1', 'da_vector_cell', '__loop418'])
    col0 = thm('colC0_eq', 'colC B2C.fs "da_verify_column__L0" "__loop420"', v['colC0'], 'colC', [],
               fs=['da_verify_column__L0', 'da_vector_cell', '__loop420'])
    dvc = thm('dvC_eq', 'dvC B2C.fs wSB', v['dvC'], 'dvC', ['colC1_eq', 'colC0_eq'],
              fs=['da_verify', 'da_row_shape', '__loop24', '__loop20', '__loop21'], sb=['da_levels__L128_L7'])
    dvs = thm('dvS_eq', 'dvS wSB wSK', v['dvS'], 'dvS colS', ['dlK_eq'],
              sk=['__loop18', '__loop19', '__loop22', '__loop23', '__loop24', '__loop417', '__loop418',
                  '__loop419', '__loop420'])
    mod('DeployedB', '`da_verify`\'s columns\' words, its constant and per row.',
        'public import LeanVM.Guest.Count.DeployedA\n',
        '\n' + col1 + '\n' + col0 + '\n/-- **`da_verify`\'s constant words.** -/\n' + dvc
        + '\n/-- **`da_verify`\'s words per row.** -/\n' + dvs)
    body = '\n'.join([
        thm('clC_eq', 'clC B2C.fs wSB', v['clC'], 'clC', ['cl_sum'], fs=['claim_list_digest', '__loop16'],
            sb=['list_split']),
        thm('ccC_eq', 'ccC B2C.fs wSB', v['ccC'], 'ccC', ['ccl_sum'], fs=['child_claim_list_digest', '__loop17'],
            sb=['list_split']),
        thm('l5A0_eq', 'l5A0 B2C.fs', v['l5A0'], 'l5A0', [], fs=['__loop5']),
        thm('l5A1_eq', 'l5A1 B2C.fs wSB', v['l5A1'], 'l5A1', ['ccC_eq'], fs=['__loop5', '__loop28'],
            sb=['da_list_digest', 'statement_digest']),
        thm('l5A2_eq', 'l5A2 B2C.fs', v['l5A2'], 'l5A2', [], fs=['__loop17', '__loop28', 'cover_da_root']),
        thm('agA0_eq', 'agA0 B2C.fs wSB', v['agA0'], 'agA0', [], fs=['aggregate_claims'],
            sb=['batch_sumcheck__L23']),
        thm('agA1_eq', 'agA1 wSK', v['agA1'], 'agA1', [], sk=['__loop25', '__loop26', '__loop27'])])
    mod('DeployedC', 'The claim lists\', the children\'s loop\'s and `aggregate_claims`\' words.',
        'public import LeanVM.Guest.Count.DeployedA2\n', '\n' + body)
    wl = words[:]
    wlit = '⟨%s⟩' % ', '.join(str(x) if i != 7 else '%d + Bv' % x for i, x in enumerate(wl))
    body = '''
/-- **The deployed budget's words**, `Bv` per child for `verify_sub`. -/
def deployedWords (Bv : ℕ) : End.Linear := %s

/-- **The deployed budget's instructions of each opcode**, `verify_sub`'s words `Bv` per child
through `__loop5`'s ratio. -/
def deployedInstrs (Bv : ℕ) : Opcode → End.Linear
''' % wlit
    for lop, P, k in ops:
        f, a5 = instrs[lop]
        parts = [str(x) for x in f]
        parts[7] = '%d + %d * (%d + Bv) / 1000' % (f[7], a5, v['l5A1'])
        body += '  | .%s => ⟨%s⟩\n' % (lop, ', '.join(parts))
    body += '''
set_option maxRecDepth 100000 in
/-- **`deployedBudget`'s words.** -/
theorem deployedBudget_words (Bv : ℕ) : (Budget.deployedBudget Bv).words = deployedWords Bv := by
  simp only [Budget.deployedBudget, Budget.mainBudget, mainWords, deployedWords]
  rw [clC_eq, dvC_eq, dvS_eq, l5A0_eq, l5A1_eq, l5A2_eq, agA0_eq, agA1_eq]
  congr 1
  all_goals omega

set_option maxRecDepth 100000 in
/-- **`deployedBudget`'s instructions.** -/
theorem deployedBudget_instrs (Bv : ℕ) (op : Opcode) :
    (Budget.deployedBudget Bv).instrs op = deployedInstrs Bv op := by
  simp only [Budget.deployedBudget, Budget.mainBudget, Budget.mainInstrs]
  rw [clC_eq, dvC_eq, dvS_eq, l5A0_eq, l5A1_eq, l5A2_eq]
  cases op <;> simp only [deployedInstrs, mainCounts, kcExp, kcDl, kcSd, kcCov, kcL0, kcL1, kcL2, kcL3,
    kcL4, kcAggC, kcAggD, krClA, krDvA, krL5A, B2C.jtSets] <;> congr 1 <;> omega
'''
    mod('Deployed', 'The numbers of the deployed budget: `deployedBudget_words`, `deployedBudget_instrs`.',
        'public import LeanVM.Guest.Count.DeployedB\npublic import LeanVM.Guest.Count.DeployedC\n', body)
    print('deployed: words', words, 'l5A1', v['l5A1'])
    for lop, _, _ in ops: print('  ', lop, instrs[lop])
    return v, words, instrs
