ESC = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "_": r"\_", "&": r"\&", "%": r"\%",
       "#": r"\#", "$": r"\$", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
BREAK_AFTER = set("._/,(:=|-")


def esc_code_breakable(s):
    out, prev = [], ""
    for c in s:
        if prev and prev.islower() and c.isupper():
            out.append(r"\allowbreak{}")
        out.append(ESC.get(c, c))
        if c in BREAK_AFTER:
            out.append(r"\allowbreak{}")
        prev = c
    return "".join(out)


def code(s):
    if len(s) <= 16 and not any(c in "#%\\{}" for c in s) and "^^" not in s:
        return r"\code{" + s + "}"
    return r"\texttt{" + esc_code_breakable(s) + "}"


def esc_plain(s, q):
    """Escape ordinary text; q is a one-element list holding the open/close state of quotes."""
    out = []
    for c in s:
        if c == '"':
            out.append("``" if not q[0] else "''")
            q[0] = not q[0]
        elif c in ESC:
            out.append(ESC[c])
        elif "Ͱ" <= c <= "Ͽ":
            out.append(r"\ensuremath{" + c + "}")
        else:
            out.append(c)
    return "".join(out).replace("--", "-{}-")


def tx(s):
    """Markdown-ish register text to LaTeX: `code`, "quotes", escapes, \\x00label\\x01 crefs."""
    q = [False]
    parts = s.split("`")
    assert len(parts) % 2 == 1, s
    out = []
    for i, p in enumerate(parts):
        if i % 2:
            out.append(code(p))
        else:
            for j, seg in enumerate(re.split(r"\x00([^\x01]*)\x01", p)):
                out.append(r"\cref{" + seg + "}" if j % 2 else esc_plain(seg, q))
    assert not q[0], ("unbalanced quotes", s)
    return "".join(out)


def sev_cell(s):
    m = re.match(r"(critical|major|minor|note)\b", s)
    if m:
        return r"\textcolor{%s}{%s}" % (m.group(1), m.group(1)) + tx(s[m.end():])
    return tx(s)


def where_cell(r):
    w, labs = boxes.where_with_refs(r["id"], r["name"], r["where"])
    w = boxes.DOSS_RE.sub(lambda m: m.group(1), w)
    return tx(w), [l for _, _, l in labs]


def dossier_plain(s):
    return tx(boxes.DOSS_RE.sub(lambda m: m.group(1), s))


def colspec(widths):
    return "@{}" + "".join(r">{\raggedright\arraybackslash}p{%.3f\linewidth}" % w for w in widths) + "@{}"


def longtable(widths, head, caption, label, body, cont_note=True):
    n = len(widths)
    h = " & ".join(r"\textbf{%s}" % x for x in head) + r" \\"
    L = [r"\begingroup\footnotesize\setlength{\tabcolsep}{4pt}",
         r"\begin{longtable}{" + colspec(widths) + "}",
         r"\caption{" + caption + r"}\label{" + label + r"}\\",
         r"\toprule", h, r"\midrule", r"\endfirsthead",
         r"\multicolumn{%d}{@{}l}{\small\itshape \tablename~\thetable, continued}\\" % n,
         r"\toprule", h, r"\midrule", r"\endhead",
         r"\midrule",
         r"\multicolumn{%d}{r@{}}{\small\itshape continued on the next page}\\" % n,
         r"\endfoot", r"\bottomrule", r"\endlastfoot"]
    L += body
    L += [r"\end{longtable}", r"\endgroup"]
    return L


def group_title(rank, sel):
    nf = len([r for r in sel if not is_position(r)])
    npos = len([r for r in sel if is_position(r)])
    t = f"{RANK_NAME[rank].capitalize()} ({nf} finding{'s' if nf != 1 else ''}"
    if npos:
        t += f", {npos} position{'s' if npos != 1 else ''}"
    return t + ")"


