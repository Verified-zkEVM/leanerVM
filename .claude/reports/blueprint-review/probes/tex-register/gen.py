def row_cells(r, with_cls):
    global ncref, crefs_total
    w, labs = where_cell(r)
    if labs:
        ncref += 1
        crefs_total += len(labs)
    c = [r"\textbf{" + r["id"] + "}", tx(r["name"]), sev_cell(r["sev"]), tx(SUBJ_NAME[r["subj"]]), w]
    if with_cls:
        c.append(tx(r["cls"]))
    c.append(tx(r["status"]))
    return " & ".join(c) + r" \\"


